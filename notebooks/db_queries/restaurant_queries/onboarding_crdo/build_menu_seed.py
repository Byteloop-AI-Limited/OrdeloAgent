"""Build menu_seed.sql for public.crdo_menu from the Deliveroo CSVs in ./deliveroo.

Usage: python3 build_menu_seed.py   (stdlib only; writes menu_seed.sql next to this file)

Conventions follow the live strk_menu: sku = sku_ordelo, sub_category 'none',
addons = {"step1": {label, required, allow_multiple, options: [{name, price_modifier}]}}.
Prints counts that menu_verify.sql re-checks against the database.
"""

import csv
import json
import os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "deliveroo")
BRANCH_LINK = "https://deliveroo.co.uk/menu/London/orpington/crispy-dosa-orpington/"


def rows(name):
    with open(os.path.join(SRC, name), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def lit(value):
    """SQL text literal (NULL for empty)."""
    if value is None or value == "":
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def modifier(value):
    """Whole pounds as int, otherwise float (matches strk_menu addons)."""
    v = float(value)
    return int(v) if v.is_integer() else v


def num(value):
    return "NULL" if value in (None, "") else str(value)


def main():
    items = [r for r in rows("menu_items.csv") if r["is_active"] == "true"]
    groups, options = {}, {}
    for g in rows("option_groups.csv"):
        groups.setdefault(g["item_key"], []).append(g)
    for o in rows("options.csv"):
        options.setdefault(o["group_key"], []).append(o)

    seen_sku, out, notes = Counter(), [], []
    for n, it in enumerate(items, 1):
        sku = it["sku_ordelo"]
        seen_sku[sku] += 1
        if seen_sku[sku] > 1:  # same title listed in two categories (Mini Idly)
            cat_slug = "".join(c if c.isalnum() else "_" for c in it["category"].lower()).strip("_")
            sku = f"{sku}_{cat_slug}"
            notes.append(f"duplicate title '{it['title']}' in {it['category']} -> sku {sku}")
        availability = it["availability"]

        addons, step = {}, 0
        for g in sorted(groups.get(it["item_key"], []), key=lambda x: int(x["step_index"])):
            opts = [o for o in sorted(options.get(g["group_key"], []), key=lambda x: int(x["option_index"]))
                    if o["is_available"] == "true"]
            required = g["is_required"] == "true"
            if not opts:
                if required and availability != "out of stock":
                    availability = "out of stock"
                    notes.append(f"'{it['title']}' set out of stock: required step '{g['label']}' has no available option")
                continue
            step += 1
            addons[f"step{step}"] = {
                "label": g["label"],
                "required": required,
                "allow_multiple": g["max_select"] != "1",
                "options": [{"name": o["name"], "price_modifier": modifier(o["price_modifier"])} for o in opts],
            }
        addons_sql = "NULL" if not addons else lit(json.dumps(addons, ensure_ascii=False)) + "::jsonb"
        out.append(
            "(%d,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)" % (
                n, lit(it["title"]), lit(sku), lit(it["description"]), lit(availability),
                num(it["price"]), lit(it["image_link"]), lit(it["category"]), "'none'",
                num(it["discounted_price"]), lit(it["dietary_requirements"]), addons_sql,
            )
        )

    sql = f"""-- crdo_menu seed: {len(out)} Deliveroo items. GENERATED by build_menu_seed.py: do not hand-edit.
-- Source: {BRANCH_LINK} (extracted 2026-11-12). Prices are Deliveroo prices.
-- Refuses a non-empty table (WHERE NOT EXISTS), so a re-run never duplicates rows.
-- Not executed by the agent. Run core/menus.sql first, then this, then menu_verify.sql.
INSERT INTO public.crdo_menu
  (id,title,sku,description,availability,price,image_link,category,sub_category,discounted_price,dietary_requirements,addons)
SELECT v.* FROM (VALUES
{(","+chr(10)).join(out)}
) AS v(id,title,sku,description,availability,price,image_link,category,sub_category,discounted_price,dietary_requirements,addons)
WHERE NOT EXISTS (SELECT 1 FROM public.crdo_menu)
RETURNING id,title,sku,availability,price;
"""
    with open(os.path.join(HERE, "menu_seed.sql"), "w", encoding="utf-8") as f:
        f.write(sql)

    cats = Counter(r["category"] for r in items)
    out_of_stock = sum(1 for r in out if "'out of stock'" in r)
    print(f"rows={len(out)} categories={len(cats)} out_of_stock={out_of_stock}")
    print(f"items_with_addons={sum(1 for r in out if '::jsonb)' in r)}")
    for c, k in cats.items():
        print(f"  {c}: {k}")
    for note in notes:
        print("NOTE:", note)


if __name__ == "__main__":
    main()
