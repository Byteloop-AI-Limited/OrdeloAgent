-- ---------------------------------------------------------------------------------------------
-- table rider_registrations
--   Rider applications: identity, vehicle, documents, bank details and review flags.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.rider_registrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    inserted_at timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
    rider_id text,
    full_name text,
    email text,
    phone text,
    phone_verified boolean NOT NULL DEFAULT FALSE,
    area text,
    postcode text,
    address text,
    dob date,
    vehicle_type text,
    license text,
    insurance text,
    gov_id text,
    right_to_work text,
    bank_account_name text,
    bank_account text,
    sort_code text,
    manual_onboard boolean NOT NULL DEFAULT FALSE,
    rider_status_active boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT rider_registrations_pkey PRIMARY KEY (id)
);

COMMENT ON COLUMN public.rider_registrations.manual_onboard IS 'check if the rider is manually onboarded or not';

