# ---- take / finish ----------------------------------------------------------------------------------------------------

def test_take_returns_the_alert_without_the_code_and_finish_accepts(db):
    code = issue(db)
    assert claim(db, code) == "ok"
    lease = uuid4()
    out = take(db, lease)
    assert out == {"result": "ok", "update_id": 1001, "phone_tail": PHONE[-4:], "tuid": TUID, "username": "rider_test",
                   "previous_tuid": None, "previous_username": None, "accepted": []}
    assert code not in json.dumps(out) and "invite_code" not in out and "code" not in out
    assert alert_row(db)[0] == "sending" and alert_row(db)[2] is not None
    assert take(db, uuid4())["result"] == "empty"   # leased rows are not due
    assert finish(db, 1001, lease, "accepted", ["440000000001"]) == "ok"
    result, next_at, lease_after, accepted, ambiguous = alert_row(db)
    assert (result, next_at, lease_after, accepted, ambiguous) == ("accepted", None, None, ["440000000001"], 0)
    assert job(db) is True and posts(db) == []


@pytest.mark.parametrize("result, ambiguous", [("retry", 0), ("ambiguous", 1)])
def test_retry_and_ambiguous_reschedule_one_minute_later(db, result, ambiguous):
    assert claim(db, issue(db)) == "ok"
    lease = uuid4()
    take(db, lease)
    assert finish(db, 1001, lease, result) == "ok"
    row = alert_row(db)
    assert row[0] == result and row[2] is None and row[4] == ambiguous
    assert rpc(db, "SELECT rider_alert_next_at BETWEEN now() + interval '50 seconds' AND now() + interval '70 seconds'"
                   " FROM public.t_invites WHERE rider_claim_update_id = 1001")


def test_stale_lease_and_invalid_result(db):
    assert claim(db, issue(db)) == "ok"
    lease = uuid4()
    take(db, lease)
    assert finish(db, 1001, uuid4(), "accepted") == "stale"
    assert finish(db, 1001, lease, "bogus") == "invalid"
    assert alert_row(db)[0] == "sending"
    assert rpc(db, "SELECT public.t_rider_invite_alert_take(NULL)")["result"] == "empty"


def test_an_expired_lease_is_retaken_counts_as_ambiguous_and_fences_the_old_sweep(db):
    assert claim(db, issue(db)) == "ok"
    old = uuid4()
    take(db, old)
    make_due(db)                                   # the first sweep died: its 2-minute lease ran out
    new = uuid4()
    assert take(db, new)["result"] == "ok"
    assert alert_row(db)[4] == 1                   # ambiguous count +1
    assert finish(db, 1001, old, "accepted") == "stale"
    assert finish(db, 1001, new, "accepted") == "ok"


def test_accepted_recipients_merge_across_attempts(db):
    assert claim(db, issue(db)) == "ok"
    first = uuid4()
    take(db, first)
    assert finish(db, 1001, first, "ambiguous", ["440000000001"]) == "ok"
    make_due(db)
    second = uuid4()
    assert take(db, second)["accepted"] == ["440000000001"]   # the sweep skips who already has it
    assert finish(db, 1001, second, "accepted", ["440000000002"]) == "ok"
    assert sorted(alert_row(db)[3]) == ["440000000001", "440000000002"]
    assert alert_row(db)[1] is None


