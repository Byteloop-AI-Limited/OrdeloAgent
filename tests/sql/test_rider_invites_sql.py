"""Rider invites on isolated Postgres: telegram/t_rider_invites.sql (issue, revoke, claim, alert take/finish), the
rest_admin isolation in telegram/t_invites.sql, and telegram/job_rider_invite_alerts.sql (ADR 0019).

Invite codes are generated by the database and only ever compared, never printed. Phones are fake (Ofcom drama range).
"""

import json
from uuid import uuid4

import pytest

from .conftest import fetch_one

pytestmark = pytest.mark.usefixtures("sql_env")

PHONE = "447700900123"
OTHER_PHONE = "447700900456"
TUID = 990000000001
HOOK = "https://app.example.test/rider-hooks/invite-alerts"


@pytest.fixture(autouse=True)
def clean(db):
    db.execute("TRUNCATE public.t_invites, public.rider_master, public.http_calls, public.http_curlopts CASCADE")
    db.execute("UPDATE public.http_stub_status SET status = 200")
    db.execute("INSERT INTO public.ordelo_config (config_key, config_value) VALUES ('ORDELO_APP_URL', 'https://app.example.test') "
               "ON CONFLICT (config_key) DO UPDATE SET config_value = EXCLUDED.config_value")
    yield
    db.execute("UPDATE public.http_stub_status SET status = 200")


def rpc(db, sql, args=()):
    return fetch_one(db, sql, args)


def issue(db, phone=PHONE):
    out = rpc(db, "SELECT public.t_rider_invite_issue(%s)", (phone,))
    assert out["result"] == "ok"
    return out["code"]


def claim(db, code, update_id=1001, tuid=TUID, tcid=None, username="rider_test", first_name="Test"):
    return rpc(db, "SELECT public.t_rider_invite_claim(%s, %s, %s, %s, %s, %s)",
               (code, update_id, tuid, tcid or tuid, username, first_name))["result"]


def take(db, lease):
    return rpc(db, "SELECT public.t_rider_invite_alert_take(%s)", (str(lease),))


def finish(db, update_id, lease, result, accepted=()):
    return rpc(db, "SELECT public.t_rider_invite_alert_finish(%s, %s, %s, %s)",
               (update_id, str(lease), result, list(accepted)))["result"]


def alert_row(db, update_id=1001):
    return db.execute(
        "SELECT rider_alert_result, rider_alert_next_at, rider_alert_lease, rider_alert_accepted, rider_alert_ambiguous_count"
        " FROM public.t_invites WHERE rider_claim_update_id = %s", (update_id,)).fetchone()


def make_due(db, update_id=1001):
    db.execute("UPDATE public.t_invites SET rider_alert_next_at = now() - interval '1 second' WHERE rider_claim_update_id = %s",
               (update_id,))


def job(db):
    return rpc(db, "SELECT public.job_rider_invite_alerts()")


def posts(db):
    return db.execute("SELECT url, body FROM public.http_calls ORDER BY id").fetchall()


# ---- issue / revoke ---------------------------------------------------------------------------------------------------

def test_issue_creates_a_placeholder_rider_and_returns_the_same_pending_code(db):
    first = issue(db, "+44 7700 900123")
    assert issue(db, PHONE) == first
    assert rpc(db, "SELECT count(*) FROM public.t_invites WHERE bot_key = 'rider' AND phone_number = %s", (PHONE,)) == 1
    row = db.execute("SELECT rider_name, town, vehicle_type, status FROM public.rider_master WHERE rider_id = %s", (PHONE,)).fetchone()
    assert row == ("TBD", "TBD", "TBD", "inactive")
    shape = db.execute("SELECT rest_ref, expires_at, status FROM public.t_invites WHERE phone_number = %s", (PHONE,)).fetchone()
    assert shape == (None, None, "pending")


@pytest.mark.parametrize("phone", ["", "abc", "12", "+0 7700 900123", "4477009001234567"])
def test_issue_and_revoke_refuse_bad_phones(db, phone):
    assert rpc(db, "SELECT public.t_rider_invite_issue(%s)", (phone,))["result"] == "bad_phone"
    assert rpc(db, "SELECT public.t_rider_invite_revoke(%s)", (phone,))["result"] == "bad_phone"


def test_revoke_only_the_pending_invite(db):
    assert rpc(db, "SELECT public.t_rider_invite_revoke(%s)", (PHONE,))["result"] == "no_pending"
    first = issue(db)
    assert rpc(db, "SELECT public.t_rider_invite_revoke(%s)", (PHONE,))["result"] == "ok"
    assert claim(db, first) == "unavailable"
    assert issue(db) != first   # a fresh code after a revoke


# ---- claim ------------------------------------------------------------------------------------------------------------

def test_claim_links_the_rider_and_queues_exactly_one_due_alert(db):
    code = issue(db)
    assert claim(db, code) == "ok"
    rider = db.execute("SELECT tuid, channel, rider_name, status, invite_profile_update_id FROM public.rider_master WHERE rider_id = %s",
                       (PHONE,)).fetchone()
    assert rider == (TUID, "telegram", "Test", "inactive", 1001)
    result, next_at, lease, accepted, ambiguous = alert_row(db)
    assert (result, lease, accepted, ambiguous) == ("pending", None, [], 0)
    assert rpc(db, "SELECT rider_alert_next_at <= now() FROM public.t_invites WHERE rider_claim_update_id = 1001")
    # A webhook retry of the same update is a replay and queues nothing new.
    assert claim(db, code) == "replay"
    assert rpc(db, "SELECT count(*) FROM public.t_invites WHERE rider_alert_next_at IS NOT NULL") == 1
    assert alert_row(db)[0] == "pending"


def test_claim_refuses_reuse_bad_codes_and_a_taken_telegram_account(db):
    code = issue(db)
    assert claim(db, "ri_" + "x" * 31) == "unavailable"            # not the code shape
    assert claim(db, "ri_" + "Z" * 32) == "unavailable"            # well formed, unknown
    db.execute("INSERT INTO public.rider_master (rider_id, rider_name, tuid, tcid) VALUES (%s, 'Someone', %s, %s)",
               (OTHER_PHONE, TUID, TUID))
    assert claim(db, code) == "tuid_taken"
    assert claim(db, code, tuid=TUID + 1) == "ok"
    assert claim(db, code, update_id=1002, tuid=TUID + 1) == "unavailable"   # already used: a new update is not a replay
    assert claim(db, code, update_id=1001, tuid=TUID + 2) == "unavailable"   # same update, different person


# ---- invite profile (t_rider_set_invite_profile, telegram/t_rider_onboarding.sql) --------------------------------------

def test_invite_claim_profile_is_fenced_by_the_claim_and_activates_on_the_final_choice(db):
    db.execute("INSERT INTO public.rider_master (rider_id, rider_name, town, vehicle_type, status) VALUES (%s, 'Seed', 'Testtown', 'bike', 'active')",
               (OTHER_PHONE,))                                  # gives t_rider_choices() a town and a vehicle to offer
    assert claim(db, issue(db)) == "ok"
    assert rpc(db, "SELECT public.t_rider_profile(%s)", (TUID,))["invite_claim"] == 1001
    sip = "SELECT public.t_rider_set_invite_profile(%s, %s, %s, %s)"
    assert rpc(db, sip, (TUID, "testtown", None, 9999))["result"] == "stale"
    assert rpc(db, "SELECT public.t_rider_set_profile(%s, %s, NULL)", (TUID, "testtown"))["result"] == "stale"   # ordinary path fenced too
    first = rpc(db, sip, (TUID, "testtown", None, 1001))
    assert (first["result"], first["town"], first["status"], first["needs_profile"]) == ("ok", "Testtown", "inactive", True)
    final = rpc(db, sip, (TUID, None, "bike", 1001))
    assert (final["result"], final["vehicle_type"], final["status"], final["needs_profile"]) == ("ok", "bike", "active", False)
    assert rpc(db, "SELECT invite_profile_update_id FROM public.rider_master WHERE rider_id = %s", (PHONE,)) is None
    assert rpc(db, sip, (TUID, None, "bike", 1001))["result"] == "stale"   # the claim reference is spent


# ---- legacy restaurant path never sees rider rows -----------------------------------------------------------------------

def test_rest_admin_readers_ignore_rider_rows(db):
    code = issue(db)
    assert claim(db, code) == "ok"
    assert rpc(db, "SELECT public.t_invite_preview(%s, 'rider', %s)", (code, TUID))["result"] == "unknown"
    assert rpc(db, "SELECT public.t_claim_invite(%s, 'rider', %s, %s, 'x', 'x')", (code, TUID, TUID))["result"] == "unknown"
    assert rpc(db, "SELECT public.t_linked_restaurants('rider', %s)", (TUID,)) == []
    assert rpc(db, "SELECT count(*) FROM public.t_invites_shareable WHERE bot_key = 'rider'") == 0
    assert db.execute("SELECT * FROM public.t_admin_restaurants('rider', %s)", (TUID,)).fetchall() == []
    # The one phone-keyed legacy reader: a claimed rider row for the same phone never names the rider in "by X".
    assert rpc(db, "SELECT public.restaurant_admin_label(%s)", (PHONE,)) == "…" + PHONE[-4:]
    # admin_roster_status, t_order_admin_phone and t_order_card_destinations join on rest_ref, which rider rows never have.


def test_scope_checks_reject_mixed_rows(db):
    import psycopg

    with pytest.raises(psycopg.errors.CheckViolation):   # a rider row with a restaurant
        db.execute("INSERT INTO public.t_invites (invite_code, bot_key, rest_ref, phone_number, expires_at)"
                   " VALUES ('ri_' || repeat('A', 32), 'rider', NULL, %s, now())", (PHONE,))
    with pytest.raises(psycopg.errors.CheckViolation):   # a rider code of the wrong shape
        db.execute("INSERT INTO public.t_invites (invite_code, bot_key, phone_number, expires_at)"
                   " VALUES ('short', 'rider', %s, NULL)", (PHONE,))


