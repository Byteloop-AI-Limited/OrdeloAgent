"""Alert Hooks Router

This router processes alert events generated by database triggers or other
services that need to notify the OrdeloAgent service about delivery failures
or other exceptional situations.

Current endpoints:
    POST /failure-notifications – processes failure notifications.

The implementation is intentionally minimal; it follows the existing patterns
in other routers and can be extended later to add real business logic.
"""

from fastapi import APIRouter, Depends, Request
from loguru import logger
import psycopg

# ---------------------------------------------------------------------------
# Dependencies
# ---------------------------------------------------------------------------


async def get_payload(request: Request):
    """Return request body as JSON (may be empty)."""
    try:
        return await request.json()
    except Exception:
        # In case of an empty body or invalid JSON we still return an empty dict.
        return {}


async def get_pool(request: Request):
    """Return the async connection pool stored in FastAPI app state."""
    return request.app.state.pool


# ---------------------------------------------------------------------------
# Router & Endpoints
# ---------------------------------------------------------------------------

router = APIRouter(tags=["alert_hooks"])


@router.post(
    "/failure-notifications",
    summary="Process Failure Notifications",
    description=(
        "Receives failure-notification webhooks from the database trigger layer. "
        "At the moment the endpoint only logs the incoming payload and returns "
        "`{\"status\": \"success\"}` so that database webhook functions can "
        "treat the call as successful. Real notification logic can be added later."
    ),
    response_description="Operation status JSON",
    responses={
        200: {
            "description": "Successfully processed the failure notification",
            "content": {"application/json": {"example": {"status": "success"}}},
        }
    },
)
async def failure_notifications(
    payload: dict = Depends(get_payload),
    pool: psycopg.AsyncConnection = Depends(get_pool),
):
    """Handle a failure notification webhook.

    The handler currently logs the payload. Business logic such as notifying
    riders/customers or updating database tables can be wired in here later.
    """

    logger.info("Received failure notification payload: {}", payload)

    # TODO: add business logic here (update tables, send WhatsApp messages, etc.)

    return {"status": "success"}
