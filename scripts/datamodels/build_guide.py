"""Build the database guide from the SQL files.

    python scripts/datamodels/build_guide.py            # write catalog.json, ordelo-database-guide.md, ordelo-database-guide.html
    python scripts/datamodels/build_guide.py --check    # exit 1 if the committed files differ from what would be built

The output is deterministic (no timestamps), so tests/test_datamodels_standard.py can compare it with the committed files.
Inputs: the SQL files (headers + text), ordelo_datamodels/guide_content.json (capabilities and flows, hand-written),
ordelo_datamodels/external_objects.json (objects owned elsewhere). Never edit the generated files by hand.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import catalog as cat  # noqa: E402

HERE = Path(__file__).resolve().parent
DM = cat.DATAMODELS
OUT_JSON, OUT_MD, OUT_HTML = DM / "catalog.json", DM / "ordelo-database-guide.md", DM / "ordelo-database-guide.html"


def load_inputs() -> tuple[dict, dict, dict]:
    c = cat.build_catalog()
    content = json.loads((DM / "guide_content.json").read_text(encoding="utf-8"))
    ext = json.loads((DM / "external_objects.json").read_text(encoding="utf-8"))
    return c, content, ext


def object_line(name: str, kind: str, text: str, header_len: int) -> int | None:
    """1-based line of the object's CREATE statement (or None)."""
    word = {"table": "TABLE", "function": "(?:FUNCTION|PROCEDURE)", "trigger": "TRIGGER", "view": "(?:MATERIALIZED\\s+)?VIEW"}.get(kind)
    if not word:
        return None
    pat = re.compile(rf'^\s*CREATE\s+(?:OR\s+REPLACE\s+)?(?:UNIQUE\s+)?{word}\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:public\.)?"?{re.escape(name)}"?\b', re.I)
    for i, ln in enumerate(text.split("\n"), 1):
        if i > header_len and pat.match(ln):
            return i
    return None


def cron_function(command: str) -> str | None:
    m = re.search(r"(?:public\.)?([A-Za-z_][A-Za-z0-9_]*)\s*\(", command)
    return m.group(1) if m and m.group(1).upper() != "SELECT" else None


def unscheduled(c: dict) -> list[str]:
    called = " ".join(j["command"] for j in c["cron"])
    notes = []
    for name, o in c["objects"].items():
        if o["kind"] == "function" and o["role"] == "definition" and (name.startswith("job_") or name == "t_housekeeping"):
            if not re.search(rf"\b{re.escape(name)}\s*\(", called):
                notes.append(f"{name}() has no pg_cron job ({o['file']}).")
    return notes


def stamp(c: dict) -> str:
    dates = []
    for f in c["files"]:
        dates += re.findall(r"\((\d{4}-\d{2}-\d{2})\)", f.get("sections", {}).get("LIVE CHECK", ""))
    return f"Checked against the live database on {max(dates)}" if dates else "Live check date unknown"


def enrich(c: dict) -> dict:
    texts = {f["path"]: (DM / f["path"]).read_text(encoding="utf-8") for f in c["files"]}
    for f in c["files"]:
        f["header_lines"] = len(cat.header_lines(texts[f["path"]])) if f["role"] in ("definition", "orphan") else 0
    by = {f["path"]: f for f in c["files"]}
    for name, o in c["objects"].items():
        f = by[o["file"]]
        o["line"] = object_line(name, o["kind"], texts[o["file"]], f["header_lines"])
    for j in c["cron"]:
        j["function"] = cron_function(j["command"])
    c["cron_notes"] = unscheduled(c)
    c["stamp"] = stamp(c)
    c["_texts"] = texts
    return c


def md_cell(s: str) -> str:
    return (s or "").replace("|", "\\|").replace("\n", " ").strip()


def build_md(c: dict, content: dict, ext: dict) -> str:
    caps = content["capabilities"]
    out = [
        "# Ordelo database guide",
        "",
        "> Generated by `scripts/datamodels/build_guide.py` from the headers of the SQL files. Do not edit by hand.",
        f"> {c['stamp']}. Interactive version with the SQL viewer: `ordelo-database-guide.html`.",
        "",
        "The SQL under `ordelo_datamodels/` is organised by capability. Each file starts with a fixed header (live check, objects, "
        "how to run, side effects, how it fits, lifecycle, callers, Python model, security, tests, gotchas, see also). "
        "The file is the authority; this guide only indexes it.",
        "",
    ]
    kinds: dict[str, int] = {}
    for o in c["objects"].values():
        kinds[o["kind"]] = kinds.get(o["kind"], 0) + 1
    out += [
        f"**{len(c['files'])} SQL files · {len(c['objects'])} objects** "
        + " · ".join(f"{n} {k}s" for k, n in sorted(kinds.items()))
        + f" · {len(c['cron'])} cron jobs",
        "",
        "## Capability map",
        "",
        "| Folder | Capability | Files | Objects | What it covers |",
        "|---|---|---:|---:|---|",
    ]
    for cap in caps:
        fs = [f for f in c["files"] if f["folder"] == cap["folder"]]
        n = sum(len(f["objects"]) for f in fs)
        out.append(f"| [`{cap['folder']}/`]({cap['folder']}/) | {cap['title']} | {len(fs)} | {n} | {md_cell(cap['summary'])} |")
    out += ["", "## Flows", ""]
    for fl in content["flows"]:
        out += [f"### {fl['title']}", "", fl["summary"], ""]
        for s in fl["steps"]:
            objs = ", ".join(f"`{o}`" for o in s["objects"])
            out.append(f"- **{s['title']}** — {s['text']} ({objs})")
        out.append("")
    out += ["## Files and objects", ""]
    for cap in caps:
        fs = [f for f in c["files"] if f["folder"] == cap["folder"]]
        if not fs:
            continue
        out += [f"### {cap['title']} (`{cap['folder']}/`)", ""]
        if cap["folder"] in ("migrations",):
            out += ["| File | Applied to live | Current definitions |", "|---|---|---|"]
            for f in fs:
                m = f["migration"]
                out.append(f"| [`{f['path']}`]({f['path']}) | {md_cell(m['applied'])} | {md_cell(', '.join(m['current']))} |")
            out.append("")
            continue
        out += ["| File | Object | Kind | What it does |", "|---|---|---|---|"]
        for f in fs:
            link = f"[`{f['path'].split('/')[-1]}`]({f['path']})"
            if not f["objects"]:
                out.append(f"| {link} | | script | {md_cell(f['title'])} |")
            for o in f["objects"]:
                if o["kind"] == "alter":
                    out.append(f"| {link} | `{o['name']}` | additions | {md_cell(o['description'])} |")
                else:
                    out.append(f"| {link} | `{o['name']}` | {o['kind']} | {md_cell(o['description'])} |")
        out.append("")
    out += [
        "## Cron jobs", "",
        "Schedule and state below come from the runnable SQL files; they are targets, not a live catalog read. "
        "At the 22 Oct R5-R6 check, `job_pause_sweep` was active on live every five minutes while its file targets every minute.",
        "", "| Job | File schedule | File state | Runs | File |", "|---|---|---|---|---|",
    ]
    for j in c["cron"]:
        out.append(f"| `{j['job']}` | {j['schedule']} | {'active' if j['active'] else 'inactive'} | `{j['function'] or j['command']}` | [`{j['file']}`]({j['file']}) |")
    if c["cron_notes"]:
        out += ["", "Job-style functions with no pg_cron job on live (some are called from Python instead):", ""] + [f"- {n}" for n in c["cron_notes"]]
    out += [
        "",
        "## Orphan candidates",
        "",
        "Live objects that nothing in OrdeloAgent, restaurant-frontend or restaurant-agents calls. Nothing has been dropped (`docs/to-do.md`).",
        "",
        "| Object | Kind | Why | File |",
        "|---|---|---|---|",
    ]
    for n, o in c["objects"].items():
        if o["role"] == "orphan":
            out.append(f"| `{n}` | {o['kind']} | {md_cell(o['description'])} | [`{o['file']}`]({o['file']}) |")
    out += ["", "## Owned by other repos", "", "| Object | Kind | Owner and file |", "|---|---|---|"]
    for n, e in ext["external"].items():
        out.append(f"| `{n}` | {e['kind']} | {e['owner']}: `{e['file']}`{' (' + e['note'] + ')' if e.get('note') else ''} |")
    out += ["", "OrdeloAgent adds to these:", ""]
    for t, a in ext["additions"].items():
        out.append(f"- `{t}`: columns {', '.join(a['columns']) or 'none'}; constraints/indexes {', '.join(a['constraints'] + a['indexes']) or 'none'} (`{a['file']}`)")
    out += ["", "Library tables: " + ", ".join(f"`{k}` ({v['owner']})" for k, v in ext["library"].items()) + ".", ""]
    return "\n".join(out).rstrip() + "\n"


def json_for_script(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, sort_keys=True).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")


def build_html(c: dict, content: dict, ext: dict) -> str:
    data = {
        "stamp": c["stamp"],
        "capabilities": content["capabilities"],
        "flows": content["flows"],
        "files": [{k: v for k, v in f.items() if k not in ("called_by", "see_also", "tests", "requires")} for f in c["files"]],
        "objects": c["objects"],
        "cron": c["cron"],
        "cron_notes": c["cron_notes"],
        "external": ext,
    }
    tpl = (HERE / "guide_template.html").read_text(encoding="utf-8")
    hl = (HERE / "vendor" / "highlight.min.js").read_text(encoding="utf-8")
    pg = (HERE / "vendor" / "pgsql.min.js").read_text(encoding="utf-8")
    sql = {p: t for p, t in c["_texts"].items()}
    for k, v in (("__DATA__", json_for_script(data)), ("__SQL__", json_for_script(sql)), ("__HLJS__", hl), ("__HLJS_PGSQL__", pg)):
        tpl = tpl.replace(k, v.replace("</script", "<\\/script") if k.startswith("__HLJS") else v)
    return tpl


def build_all() -> dict[Path, str]:
    c, content, ext = load_inputs()
    c = enrich(c)
    texts = c.pop("_texts")
    pub = json.dumps({k: v for k, v in c.items()}, indent=1, ensure_ascii=False, sort_keys=True) + "\n"
    c["_texts"] = texts
    return {OUT_JSON: pub, OUT_MD: build_md(c, content, ext), OUT_HTML: build_html(c, content, ext)}


def main(argv: list[str]) -> int:
    built = build_all()
    if "--check" in argv:
        stale = [p.name for p, t in built.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            print("stale (run python scripts/datamodels/build_guide.py):", ", ".join(stale))
            return 1
        print("guide is up to date")
        return 0
    for p, t in built.items():
        p.write_text(t, encoding="utf-8")
        print(f"wrote {p.relative_to(cat.ROOT)} ({len(t):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
